#!/usr/bin/env node
'use strict';

const path = require('path');
const fs = require('fs');
const readline = require('readline');

const ASSETS_SCRIPTS = path.join(__dirname, '..', 'assets', 'scripts');
const DEFAULT_API_URL = 'https://hd-erp-permission.dev.hdwebsoft.co';
const DEFAULT_DOCS_DIR = 'docs';

function copyDirSync(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirSync(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function ask(rl, question) {
  return new Promise((resolve) => rl.question(question, resolve));
}

function generateWorkflowYaml({ branches, docsDir, apiUrl }) {
  const branchLines = branches.map((b) => `      - ${b}`).join('\n');
  const cleanDocsDir = docsDir.replace(/^\/+|\/+$/g, '') || DEFAULT_DOCS_DIR;

  return `name: HD ERP Docs Sync

on:
  push:
    branches:
${branchLines}
    paths:
      - '${cleanDocsDir}/**'
      - '.erp-docs.config.json'
      - 'scripts/docs-sync/**'
  workflow_dispatch:

jobs:
  sync-docs:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Run HD ERP Docs Sync
        env:
          PERMISSION_API_PUBLIC_URL: \${{ vars.PERMISSION_API_PUBLIC_URL || '${apiUrl}' }}
          ERP_DOCS_SYNC_TOKEN: \${{ secrets.ERP_DOCS_SYNC_TOKEN }}
        run: |
          chmod +x scripts/docs-sync/run.sh
          sh scripts/docs-sync/run.sh
`;
}

async function main() {
  const cwd = process.cwd();
  console.log('\n🔧 HD ERP Docs Sync Setup\n');

  // Step 1: Copy scripts directory
  const destScripts = path.join(cwd, 'scripts');
  console.log(`📁 Copying scripts/ → ${destScripts}`);
  copyDirSync(ASSETS_SCRIPTS, destScripts);
  // Ensure run.sh is executable on Unix
  try {
    fs.chmodSync(path.join(destScripts, 'docs-sync', 'run.sh'), 0o755);
  } catch {}
  console.log('   ✓ Done\n');

  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

  // Step 2: Interactive prompts
  const apiUrl = (await ask(rl,
    `PERMISSION_API_PUBLIC_URL [${DEFAULT_API_URL}]: `
  )).trim() || DEFAULT_API_URL;

  const token = (await ask(rl,
    'ERP_DOCS_SYNC_TOKEN: '
  )).trim();
  if (!token) {
    rl.close();
    console.error('\n❌ ERP_DOCS_SYNC_TOKEN is required.');
    process.exit(1);
  }

  const collectionId = (await ask(rl,
    'collectionId (UUID): '
  )).trim();
  if (!collectionId) {
    rl.close();
    console.error('\n❌ collectionId is required.');
    process.exit(1);
  }

  const docsDir = (await ask(rl,
    `Docs directory [${DEFAULT_DOCS_DIR}]: `
  )).trim() || DEFAULT_DOCS_DIR;

  const cicdBranchInput = (await ask(rl,
    'CI/CD trigger branch (e.g. dev, main, master - leave blank to skip): '
  )).trim();

  rl.close();

  const cicdBranches = cicdBranchInput
    ? cicdBranchInput.split(',').map((b) => b.trim()).filter(Boolean)
    : [];

  // Step 3: Write .env.erp-docs
  const envPath = path.join(cwd, '.env.erp-docs');
  const envContent = [
    '# HD ERP Docs Sync - generated by @khoa-hd/docs-sync',
    '# DO NOT commit this file!',
    `PERMISSION_API_PUBLIC_URL=${apiUrl}`,
    `ERP_DOCS_SYNC_TOKEN=${token}`,
  ].join('\n') + '\n';

  fs.writeFileSync(envPath, envContent, 'utf8');
  console.log(`\n📄 Written: .env.erp-docs`);

  // Step 4: Write .erp-docs.config.json
  const docsRoot = docsDir.endsWith('/') ? docsDir : docsDir + '/';
  const config = {
    apiUrl: '${PERMISSION_API_PUBLIC_URL}',
    token: '${ERP_DOCS_SYNC_TOKEN}',
    envFile: '.env.erp-docs',
    collectionId,
    root: docsRoot,
    include: [`${docsDir}/**`],
    exclude: [`${docsDir}/internal/**`],
  };
  const configPath = path.join(cwd, '.erp-docs.config.json');
  fs.writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n', 'utf8');
  console.log('📄 Written: .erp-docs.config.json');

  // Step 5: Update .gitignore
  const gitignorePath = path.join(cwd, '.gitignore');
  const gitignoreContent = fs.existsSync(gitignorePath)
    ? fs.readFileSync(gitignorePath, 'utf8')
    : '';
  if (!gitignoreContent.includes('.env.erp-docs')) {
    fs.appendFileSync(gitignorePath, '\n.env.erp-docs\n', 'utf8');
    console.log('📄 Updated: .gitignore (added .env.erp-docs)');
  }

  // Step 6: Inject npm scripts into package.json if present
  const pkgPath = path.join(cwd, 'package.json');
  let npmScriptsAdded = false;
  if (fs.existsSync(pkgPath)) {
    try {
      const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
      pkg.scripts = pkg.scripts || {};
      let changed = false;
      const toAdd = {
        'docs:setup': 'docs-sync',
        'docs:sync': 'sh scripts/docs-sync/run.sh',
        'docs:sync:dry': 'sh scripts/docs-sync/run.sh --dry-run',
      };
      for (const [key, val] of Object.entries(toAdd)) {
        if (!pkg.scripts[key]) {
          pkg.scripts[key] = val;
          changed = true;
        }
      }
      if (changed) {
        fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');
        console.log('📄 Updated: package.json (added docs:setup, docs:sync, docs:sync:dry)');
        npmScriptsAdded = true;
      }
    } catch {}
  }

  console.log('\n✅ Setup complete!\n');
  console.log('Run the sync with:');
  console.log('  sh scripts/docs-sync/run.sh');
  if (npmScriptsAdded) {
    console.log('  # or via npm:');
    console.log('  npm run docs:sync');
    console.log('  npm run docs:sync:dry   # preview only');
  }
  console.log('');

  if (cicdBranches.length > 0) {
    const yamlContent = generateWorkflowYaml({
      branches: cicdBranches,
      docsDir,
      apiUrl,
    });

    console.log('─────────────────────────────────────────────────────────────────');
    console.log('🚀 Suggested CI/CD Workflow (.github/workflows/docs-sync.yml):');
    console.log('─────────────────────────────────────────────────────────────────');
    console.log(yamlContent);
    console.log('─────────────────────────────────────────────────────────────────');
    console.log('📖 Basic CI/CD Setup Instructions:');
    console.log('  1. Create file: .github/workflows/docs-sync.yml in your repository.');
    console.log('  2. Copy and paste the suggested YAML workflow above into that file.');
    console.log('  3. Configure Secret in GitHub Repository:');
    console.log('     • Go to: Settings → Secrets and variables → Actions');
    console.log('     • Click "New repository secret"');
    console.log('     • Name: ERP_DOCS_SYNC_TOKEN');
    console.log('     • Secret: paste your sync token');
    console.log('  4. (Optional) Configure Variable:');
    console.log('     • Under "Repository variables", click "New repository variable"');
    console.log('     • Name: PERMISSION_API_PUBLIC_URL');
    console.log(`     • Value: ${apiUrl}`);
    console.log(`  5. Commit & push changes on branch [${cicdBranches.join(', ')}]. Docs will sync automatically!`);
    console.log('─────────────────────────────────────────────────────────────────\n');
  } else {
    console.log('💡 CI/CD setup skipped (no branch specified).');
    console.log('   To set up CI/CD later, you can create .github/workflows/docs-sync.yml');
    console.log('   triggering on your desired branch (e.g. main, dev).\n');
  }
}

main().catch((err) => {
  console.error('Error:', err.message);
  process.exit(1);
});
